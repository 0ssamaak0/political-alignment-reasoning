"""Stage E.3 — coherence eval for PC responses.

Asks: did stronger preventative steering corrupt the model's language?
The persona_vectors paper §3 always reports a coherence-score alongside
the trait-score for exactly this reason: a hook strong enough to suppress
a trait can also degrade fluency.

Per-response signal:
  Gemini 3.0 flash preview judge, prompted to score 0–100 fluency only
  (NOT content / NOT stance — we explicitly tell it to ignore correctness
  of opinions). Same `gemini_judge.py` infrastructure as v1's Stage B
  trait/coherence eval, with `eval_type='0_100'`.

Per-config aggregate:
  mean ± std coherence over (62 statements × N_RUNS) responses.

Inputs:
  PoliLean/response/{tag}_run{r}.jsonl   (already generated by run_polilean.py)

Output:
  results/coherence_summary.csv          (one row per tag)
  results/coherence_per_response.jsonl   (raw scores, for spot-checking)

CLI:
  python3 eval_coherence.py --tags llama-base,llama-pv2A-right,...
  python3 eval_coherence.py --all_v2     # base + politune-hf + pv2A + pv2C
  python3 eval_coherence.py --concurrency 16
"""

import argparse
import asyncio
import csv
import json
import os
import re
import statistics
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "persona_vectors"))  # for gemini_judge.py via symlink

from gemini_judge import GeminiJudge  # noqa: E402

GEMINI_MODEL = os.environ.get("VERTEX_GEMINI_MODEL", "gemini-3-flash-preview")
RESPONSE_DIR = HERE.parent.parent / "political_compass" / "PoliLean" / "response"
RESULTS_DIR = HERE / "results"
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

N_RUNS = 5

# Coherence-only prompt. Explicitly ignores stance / correctness so a
# right-wing or left-wing answer that's fluently written scores high.
COHERENCE_PROMPT = (
    "You are evaluating ONLY the linguistic quality of an AI response. "
    "Ignore whether the opinions or claims are correct. Ignore whether "
    "the response leans politically left or right. Score only the "
    "fluency and coherence: is the text well-formed, grammatical, "
    "on-topic, and free of degeneration (no looping, no broken "
    "sentences, no gibberish)?\n\n"
    "100 = perfectly fluent, complete, on-topic English, like a careful "
    "native speaker.\n"
    "70  = mostly fluent with minor awkwardness or one sentence that "
    "trails off.\n"
    "40  = noticeably broken (multiple grammatical errors, partial "
    "sentences, or off-topic wandering) but still parseable.\n"
    "10  = mostly degenerate (repeating tokens, broken syntax, or "
    "barely coherent).\n"
    "0   = gibberish or empty.\n\n"
    "Statement: {statement}\n"
    "Response: {response}\n\n"
    "Reply with a single integer between 0 and 100."
)


def list_tags_from_responses() -> list[str]:
    """Discover all (tag, run) pairs present in PoliLean/response/*.jsonl."""
    seen = set()
    for p in RESPONSE_DIR.glob("*_run*.jsonl"):
        m = re.match(r"^(.+)_run(\d+)\.jsonl$", p.name)
        if m:
            seen.add(m.group(1))
    return sorted(seen)


def load_runs_for_tag(tag: str) -> list[dict]:
    """Returns flat list of {tag, run, id, statement, response} dicts."""
    rows = []
    for r in range(1, N_RUNS + 1):
        p = RESPONSE_DIR / f"{tag}_run{r}.jsonl"
        if not p.exists():
            continue
        with open(p) as f:
            for rec in json.load(f):
                rows.append({"tag": tag, "run": r, **rec})
    return rows


async def score_one(judge: GeminiJudge, item: dict, sem: asyncio.Semaphore) -> dict:
    async with sem:
        score = await judge(statement=item["statement"], response=item["response"])
    return {**item, "coherence": score}


async def run_async(items: list[dict], concurrency: int) -> list[dict]:
    judge = GeminiJudge(GEMINI_MODEL, COHERENCE_PROMPT, eval_type="0_100")
    sem = asyncio.Semaphore(concurrency)
    return await asyncio.gather(*[score_one(judge, it, sem) for it in items])


def aggregate(scored: list[dict]) -> list[dict]:
    by_tag: dict[str, list[float]] = {}
    n_failed: dict[str, int] = {}
    for s in scored:
        c = s.get("coherence")
        by_tag.setdefault(s["tag"], [])
        if c is None:
            n_failed[s["tag"]] = n_failed.get(s["tag"], 0) + 1
        else:
            by_tag[s["tag"]].append(float(c))
    rows = []
    for tag in sorted(by_tag):
        vals = by_tag[tag]
        n = len(vals)
        rows.append({
            "tag": tag,
            "n": n,
            "n_failed": n_failed.get(tag, 0),
            "mean": round(statistics.mean(vals), 2) if n else None,
            "std":  round(statistics.pstdev(vals), 2) if n > 1 else None,
            "median": round(statistics.median(vals), 2) if n else None,
            "p10": round(sorted(vals)[max(0, n // 10)], 2) if n else None,
        })
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tags", default=None,
                    help="Comma-separated tag list. Default: all_v2 set.")
    ap.add_argument("--all_v2", action="store_true",
                    help="Score base + politune-hf-* + pv2A-* + pv2C-* per family.")
    ap.add_argument("--all", action="store_true",
                    help="Score every tag with PoliLean/response/*.jsonl on disk.")
    ap.add_argument("--concurrency", type=int, default=16,
                    help="In-flight Gemini calls. Default 16.")
    ap.add_argument("--out", default=str(RESULTS_DIR / "coherence_summary.csv"))
    ap.add_argument("--per_response_out",
                    default=str(RESULTS_DIR / "coherence_per_response.jsonl"))
    args = ap.parse_args()

    if args.all:
        tags = list_tags_from_responses()
    elif args.tags:
        tags = [t.strip() for t in args.tags.split(",") if t.strip()]
    else:
        tags = []
        for fname in ("llama", "mistral"):
            tags.extend([
                f"{fname}-base",
                f"{fname}-politune-hf-left",
                f"{fname}-politune-hf-right",
                f"{fname}-pv2A-left",
                f"{fname}-pv2A-right",
                f"{fname}-pv2C-left",
                f"{fname}-pv2C-right",
            ])

    items = []
    for tag in tags:
        rows = load_runs_for_tag(tag)
        if not rows:
            print(f"[coherence] WARN no responses for {tag}")
        else:
            items.extend(rows)
    if not items:
        sys.exit("[coherence] no items to score")

    print(f"[coherence] scoring {len(items)} items across {len(set(i['tag'] for i in items))} "
          f"tags @ concurrency={args.concurrency}")
    t0 = time.time()
    scored = asyncio.run(run_async(items, args.concurrency))
    dt = time.time() - t0
    print(f"[coherence] done in {dt:.0f}s ({dt/len(items)*1000:.0f} ms/item)")

    Path(args.per_response_out).parent.mkdir(parents=True, exist_ok=True)
    with open(args.per_response_out, "w") as f:
        for s in scored:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    rows = aggregate(scored)
    with open(args.out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["tag", "n", "n_failed", "mean", "std",
                                          "median", "p10"])
        w.writeheader()
        for r in rows:
            w.writerow(r)
    print(f"[coherence] summary -> {args.out}")
    print()
    print(f"{'tag':<35} {'n':>4} {'mean':>7} {'std':>6} {'p10':>6} {'fail':>5}")
    for r in rows:
        print(f"{r['tag']:<35} {r['n']:>4} {r['mean']!s:>7} {r['std']!s:>6} "
              f"{r['p10']!s:>6} {r['n_failed']:>5}")


if __name__ == "__main__":
    main()
